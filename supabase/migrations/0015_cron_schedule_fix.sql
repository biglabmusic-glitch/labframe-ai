-- Чиним РАСПИСАНИЕ тика очереди.
--
-- В 0002_cron.sql стояло '*/10 * * * * *' с комментарием «каждые 10 секунд». На деле
-- pg_cron разбирает это как обычный пятипольный cron: '*/10' попадает в поле МИНУТ,
-- лишнее шестое поле игнорируется. Замер на проде: 6 запусков за час, то есть
-- раз в 10 минут. Для sub-minute у pg_cron 1.5+ другой синтаксис — интервал
-- ('10 seconds'), а не шесть полей.
--
-- 10 минут — бесполезная подстраховка: фронт (waitForJob) сдаётся через 6 минут,
-- то есть юзер увидит ошибку раньше, чем cron успеет подобрать осиротевший job.
--
-- Ставим раз в минуту, а не раз в 10 секунд, сознательно:
--   • после перехода на передачу jobId из create-job обычный путь cron вообще не нужен —
--     тик остался ТОЛЬКО подстраховкой на случай, если фоновый fetch не доехал;
--   • 60 секунд с запасом укладываются в 6-минутный таймаут фронта;
--   • раз в 10 секунд — это 259k вызовов Edge Functions в месяц почти вхолостую,
--     половина бесплатной квоты Supabase. Раз в минуту — 43k.
--
-- Пятипольный формат выбран намеренно: он разбирается однозначно, в отличие от
-- шестипольного, на котором и погорела исходная миграция.

select cron.schedule(
  'process-jobs-tick',
  '* * * * *',                               -- каждую минуту
  $$
  select net.http_post(
    url := 'https://mmegdmfmozgaycuyeacl.supabase.co/functions/v1/process-job',
    headers := jsonb_build_object(
      'Content-Type',      'application/json',
      'x-internal-secret', coalesce(
        (select decrypted_secret from vault.decrypted_secrets where name = 'internal_secret'),
        ''
      )
    ),
    body := '{}'::jsonb,
    timeout_milliseconds := 60000
  );
  $$
);

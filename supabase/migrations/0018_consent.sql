-- Согласие на обработку персональных данных.
--
-- Хранить факт согласия нужно на сервере, а не в localStorage: localStorage
-- чистится вместе с кэшем, привязан к устройству и ничего не доказывает.
-- Дата же — это то, чем оператор подтверждает, что согласие было получено.
--
-- Версию храним рядом: если текст политики существенно изменится, согласие
-- нужно будет собрать заново, и по номеру версии видно, у кого оно устарело.
alter table public.users
  add column if not exists consent_at      timestamptz,
  add column if not exists consent_version int;

comment on column public.users.consent_at is
  'Когда пользователь принял политику обработки персональных данных. NULL — не принимал.';
comment on column public.users.consent_version is
  'Версия текста политики, с которой согласился пользователь.';

-- Лимит размера файла на bucket-ах.
--
-- Раньше bucket-ы создавались (0001_init.sql) без file_size_limit, а /sign-upload
-- выдаёт подписанный URL, не зная размера будущего файла. То есть любой юзер мог
-- залить в свой префикс объект произвольного размера — это прямой счёт за Storage.
--
-- 20 МБ выбраны с запасом: фото с современного телефона это 3–8 МБ (HEIC/JPEG),
-- результат генерации — 1–3 МБ. Реальные загрузки под лимит не попадают.
--
-- allowed_mime_types намеренно НЕ ставим: часть мобильных WebView не проставляет
-- Content-Type при PUT, и bucket-level проверка отбила бы живые загрузки.
-- Тип проверяется в /sign-upload (принимаем только image/*).
update storage.buckets
   set file_size_limit = 20971520          -- 20 MiB
 where id in ('photos', 'brand', 'results');

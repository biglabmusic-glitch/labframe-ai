// Объяснение технического сбоя человеческим языком — для сообщения в чат.
//
// Главное, что должен снять этот текст, — страх «с меня списали, а картинки нет».
// Списания при сбое действительно не происходит: триггер spend_credits_on_done
// (миграция 0016) трогает баланс только при переходе job в 'done', а упавшая
// работа получает 'failed'. Поэтому про сохранённый баланс пишем честно и всегда.
//
// Ошибки разделены по источнику: за чужой сбой не извиняемся как за свой, но и
// не сваливаем вину на подрядчика — человеку важно понять, повторять ему попытку
// или ждать.

export interface JobFailure {
  /** Готовый текст для отправки в чат. */
  text: string;
  /** false — сломалось у внешнего сервиса, не у нас. Для админской статистики. */
  ours: boolean;
}

const RETRY = 'Генерация не списана — баланс остался прежним. Попробуйте ещё раз.';

export function explainJobFailure(raw: string): JobFailure {
  const s = (raw ?? '').toLowerCase();

  // Сеть до внешних сервисов: таймауты, отказы соединения, 5xx у подрядчика.
  if (
    s.includes('timed out') || s.includes('timeout') ||
    s.includes('connect error') || s.includes('econnrefused') ||
    s.includes('network') || s.includes('fetch failed')
  ) {
    return {
      ours: false,
      text: 'Не получилось обработать фото: сервис генерации не ответил вовремя. ' +
            'Это временный сбой на его стороне.' + '\n\n' + RETRY,
    };
  }

  // Подрядчик ответил, но ошибкой.
  if (s.includes('polza') || s.includes('replicate') || /\b5\d\d\b/.test(s)) {
    return {
      ours: false,
      text: 'Не получилось обработать фото: сервис генерации вернул ошибку. ' +
            'Обычно это ненадолго.' + '\n\n' + RETRY,
    };
  }

  // Работа простояла в очереди и была снята по таймауту (sweepStale).
  if (s.includes('not_picked_up')) {
    return {
      ours: true,
      text: 'Не получилось обработать фото: работа слишком долго ждала очереди ' +
            'и была снята.' + '\n\n' + RETRY,
    };
  }

  // Файл: не то прислали или не смогли прочитать.
  if (s.includes('unsupported_type') || s.includes('download') || s.includes('storage')) {
    return {
      ours: true,
      text: 'Не получилось обработать фото: файл не удалось прочитать. ' +
            'Попробуйте прислать другой снимок — JPG или PNG.' + '\n\n' +
            'Генерация не списана.',
    };
  }

  // Всё остальное — считаем своим: чужое мы уже разобрали выше.
  return {
    ours: true,
    text: 'Не получилось обработать фото — что-то сломалось на нашей стороне. ' +
          'Мы уже видим эту ошибку.' + '\n\n' + RETRY,
  };
}
